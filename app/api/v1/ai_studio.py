@router.post("/knowledge/ask", response_model=KnowledgeAskResult)
async def ask_knowledge(payload: KnowledgeAskRequest, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    """Answer from the knowledge base (and, with device_id, that device's live data) with numbered
    citations. If nothing relevant is found the answer says so — it does not guess."""
    if payload.device_id is not None:
        _device(db, payload.device_id)
    hits = await studio_data.kb_search(db, payload.question, payload.limit)
    live = None
    if payload.device_id is not None:
        from app.services.ai_context import gather_live_context

        live = gather_live_context(db, payload.question, device_id=payload.device_id)
    sources = [SourceRef(type="knowledge", id=h["chunk_id"], document_id=h["document_id"], title=h["document_title"], score=h["score"], excerpt=h["excerpt"]) for h in hits]
    zh = payload.lang == "zh"
    if not hits and not live:
        return KnowledgeAskResult(
            answer="知识库中没有找到与该问题相关的内容。请先在 Knowledge → Upload 导入资料，或换个说法再试。" if zh
            else "Nothing relevant was found in the knowledge base. Upload documents under Knowledge → Upload, or rephrase the question.",
            generated_by="none", grounded=False, sources=[])
    kb_text = "\n".join(f"[{i}] ({h['document_title']}) {h['excerpt']}" for i, h in enumerate(hits, 1))
    facts = ((f"PLATFORM DATA:\n{live}\n\n" if live else "") + (f"KNOWLEDGE:\n{kb_text}" if kb_text else "")).strip()
    prompt = (f"Answer the question in {'Chinese' if zh else 'English'} using ONLY the material below; cite knowledge as [n]. "
              f"If the material does not answer it, say so plainly.\n\n{facts}\n\nQuestion: {payload.question}")
    notes: list[str] = []
    llm = await _llm(db, prompt, payload.lang)
    if llm:
        bad = gen.ungrounded_numbers(llm, facts + " " + payload.question)
        if not bad:
            return KnowledgeAskResult(answer=llm, generated_by="llm", grounded=True, sources=sources, live_context_used=bool(live))
        notes.append(f"LLM answer was discarded because it contained figures not present in the sources ({', '.join(bad[:5])}); the source excerpts are shown instead.")
    head = "以下是知识库中最相关的内容（未启用生成式模型，直接引用原文）：" if zh else "Most relevant knowledge-base excerpts (no generative model enabled — quoted directly):"
    parts = [head] + [f"[{i}] {h['document_title']}：{h['excerpt']}" for i, h in enumerate(hits, 1)]
    if live:
        parts += ["", ("平台实时数据：\n" if zh else "Live platform data:\n") + live]
    return KnowledgeAskResult(answer="\n".join(parts), generated_by="extractive", grounded=True, sources=sources, live_context_used=bool(live), notes=notes)


