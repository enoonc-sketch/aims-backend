@router.post("/roi/generate", response_model=ROIResult)
async def generate_roi(payload: ROIRequest, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    """Cost-side ROI / total-cost-of-ownership from the asset, maintenance records, work orders and
    alarms — plus ROI % and payback when `annual_benefit` is supplied (the platform does not know it)."""
    device = _device(db, payload.device_id)
    asset, records, wos, alarms = studio_data.roi_inputs(db, device, payload.period_months)
    res = roi.compute_roi(asset, records, wos, alarms, payload.period_months, annual_benefit=payload.annual_benefit)
    text = gen.roi_template(res, payload.lang)
    narrative, by, notes = await _narrate(db, payload.lang, text, gen.roi_prompt(res, text, payload.lang))
    return ROIResult(device_id=device.id, device_code=device.device_code, asset_code=asset["asset_code"] if asset else None,
                     narrative=narrative, generated_by=by, notes=notes, **res)


