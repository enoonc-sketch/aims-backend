MAX_INLINE_SERIES, MAX_INLINE_POINTS = 40, 5000


def _device(db: Session, device_id: int) -> Device:
    d = db.get(Device, device_id)
    if not d:
        raise HTTPException(status_code=404, detail="Device not found")
    return d


async def _llm(db: Session, prompt: str, lang: str) -> Optional[str]:
    """LLM text, or None (no model configured / provider error). A provider failure must never
    take down a feature that has an offline template."""
    try:
        out = await _call_llm(prompt, db=db, system=gen.STRICT_SYSTEM[lang])
    except Exception:  # noqa: BLE001
        logger.exception("LLM call failed; using the offline template")
        return None
    return out.strip() if out and out.strip() else None


async def _narrate(db: Session, lang: str, facts_text: str, prompt: str) -> tuple[str, str, list[str]]:
    """(text, generated_by, notes). LLM text is accepted only if every figure in it is in `facts_text`."""
    llm = await _llm(db, prompt, lang)
    if llm:
        bad = gen.ungrounded_numbers(llm, facts_text)
        if not bad:
            return llm, "llm", []
        return facts_text, "template", [f"LLM text was discarded because it contained figures not present in the data ({', '.join(bad[:5])}); the data-derived text is shown instead."]
    return facts_text, "template", []


