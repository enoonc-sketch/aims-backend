"""AI Studio — AI-generated SOP and ROI, AI reading of Data Analysis data, knowledge-base Q&A
with citations, and the Data-Analysis-driven Lab comparison with AI certification.

Principles (see the pure modules for the details):
* every FIGURE is computed from platform data; the LLM only phrases it;
* LLM text that contains a number or specification that is not in the data it was given is
  discarded and replaced by the data-derived template (reported in `notes`);
* with no LLM configured everything still works from the templates (`generated_by: "template"`);
* generated SOPs are always drafts that need human approval.
"""
