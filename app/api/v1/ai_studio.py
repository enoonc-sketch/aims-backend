def _compare(db: Session, p: LabCompareRequest) -> tuple[Device, dict]:
    device = _device(db, p.device_id)
    return device, studio_data.lab_compare(db, device.id, p.component_name, p.window_minutes, p.aggregate, p.date_from, p.date_to)


@lab_router.post("/analysis-compare", response_model=LabCompareResult)
def analysis_compare(payload: LabCompareRequest, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    """Lab vs online comparison where the online value is taken from the analyzer's measurement
    data (what Data Analysis shows) around each sampling time — not from a typed-in value."""
    device, r = _compare(db, payload)
    return LabCompareResult(device_id=device.id, device_code=device.device_code, component_name=payload.component_name,
                            window_minutes=payload.window_minutes, aggregate=payload.aggregate, **r)


@lab_router.post("/certify", response_model=LabCertifyResult)
async def certify(payload: LabCertifyRequest, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    """AI certification: compare (as above), judge against explicit criteria, explain, and keep an
    audit record. Also refreshes the Lab correlation table from the analysis-based result.
    Not a metrological accreditation."""
    unknown = set(payload.criteria or {}) - set(la.DEFAULT_CRITERIA)
    if unknown:
        raise HTTPException(status_code=400, detail=f"Unknown criteria: {sorted(unknown)}; allowed: {sorted(la.DEFAULT_CRITERIA)}")
    device, r = _compare(db, payload)
    cert = la.certify(r["stats"], r["sample_count"], payload.criteria)
    text = gen.cert_template(device.device_code, payload.component_name, r["stats"], cert, payload.window_minutes, len(r["unmatched"]), payload.lang)
    narrative, by, notes = await _narrate(db, payload.lang, text, gen.cert_prompt(text, payload.lang))
    now = datetime.now(timezone.utc)
    valid_until = now + timedelta(days=payload.valid_days) if cert["status"] in ("certified", "conditional") else None
    cert_id = None
    if payload.persist:
        s = r["stats"]
        row = LabAICertification(
            device_id=device.id, component_name=payload.component_name, status=cert["status"], score=cert["score"],
            window_minutes=int(round(payload.window_minutes)), sample_count=r["sample_count"], pair_count=s.get("pairs", 0),
            r_squared=s.get("r_squared"), slope=s.get("slope"), intercept=s.get("intercept"), bias_pct=s.get("bias_pct"), mape_pct=s.get("mape_pct"),
            criteria=cert["criteria"], checks=cert["checks"], stats=s, narrative=narrative, generated_by=by, certified_at=now, valid_until=valid_until,
        )
        db.add(row)
        studio_data.upsert_correlation(db, device.id, payload.component_name, r["pairs"], s)
        db.commit()
        db.refresh(row)
        cert_id = row.id
    return LabCertifyResult(
        device_id=device.id, device_code=device.device_code, component_name=payload.component_name, window_minutes=payload.window_minutes,
        aggregate=payload.aggregate, status=cert["status"], score=cert["score"], checks=cert["checks"], criteria=cert["criteria"],
        disclaimer=cert["disclaimer"], narrative=narrative, generated_by=by, notes=notes, certification_id=cert_id, valid_until=valid_until, **r,
    )


@lab_router.get("/certifications", response_model=list[LabCertificationOut])
def list_certifications(
    device_id: Optional[int] = None,
    component_name: Optional[str] = None,
    latest: bool = Query(False, description="Only the newest record per device + component (the Comparison overview)"),
    limit: int = Query(100, ge=1, le=500),
    db: Session = Depends(get_db),
):
    if latest:
        # newest id per (device_id, component_name), computed in SQL rather than fetched-then-deduped in
        # Python, so it is correct no matter how many historical rows exist for a device + component.
        ids = studio_data.latest_certification_ids(db, device_id, component_name)
        rows = db.scalars(select(LabAICertification).where(LabAICertification.id.in_(ids)).order_by(LabAICertification.id.desc())).all() if ids else []
        rows = rows[:limit]
    else:
        q = select(LabAICertification)
        if device_id is not None:
            q = q.where(LabAICertification.device_id == device_id)
        if component_name:
            q = q.where(LabAICertification.component_name == component_name)
        rows = db.scalars(q.order_by(LabAICertification.id.desc()).limit(limit)).all()
    codes = dict(db.execute(select(Device.id, Device.device_code)).all())
    now = datetime.now(timezone.utc)
    out = []
    for r in rows:
        vu = r.valid_until
        if vu is not None and vu.tzinfo is None:
            vu = vu.replace(tzinfo=timezone.utc)
        out.append(LabCertificationOut(
            id=r.id, device_id=r.device_id, device_code=codes.get(r.device_id), component_name=r.component_name, status=r.status,
            score=float(r.score) if r.score is not None else None, window_minutes=r.window_minutes, sample_count=r.sample_count, pair_count=r.pair_count,
            r_squared=float(r.r_squared) if r.r_squared is not None else None, bias_pct=float(r.bias_pct) if r.bias_pct is not None else None,
            mape_pct=float(r.mape_pct) if r.mape_pct is not None else None, generated_by=r.generated_by, narrative=r.narrative, checks=r.checks,
            certified_at=r.certified_at, valid_until=r.valid_until, expired=bool(vu is not None and vu < now), disclaimer=la.DISCLAIMER,
        ))
    return out
