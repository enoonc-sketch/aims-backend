@router.post("/analysis/read", response_model=AnalysisReadResult)
async def read_analysis(payload: AnalysisReadRequest, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    """AI reads Data Analysis data: per-series stats, trend, outliers, stuck/missing readings,
    component-sum check and correlations, then a short interpretation. Works on server data
    (device + components + hours) or on series sent inline (e.g. the sheet open in the browser)."""
    if payload.series is not None:
        if not payload.series or len(payload.series) > MAX_INLINE_SERIES:
            raise HTTPException(status_code=400, detail=f"series must contain 1-{MAX_INLINE_SERIES} entries")
        if any(len(v) > MAX_INLINE_POINTS for v in payload.series.values()):
            raise HTTPException(status_code=400, detail=f"each series may have at most {MAX_INLINE_POINTS} points")
        series, source = payload.series, "inline"
    elif payload.device_id is not None:
        _device(db, payload.device_id)
        comps = payload.components or studio_data.device_component_names(db, payload.device_id)
        if not comps:
            raise HTTPException(status_code=400, detail="The device has no components/TAGs to read")
        found = studio_data.series_from_db(db, payload.device_id, comps[:MAX_INLINE_SERIES], payload.hours)
        series, source = {c: found.get(c, []) for c in comps[:MAX_INLINE_SERIES]}, "server"
    else:
        raise HTTPException(status_code=400, detail="Provide device_id or series")

    res = ar.read_series(series, check_sum=payload.check_sum)
    text = gen.reading_template(res, payload.lang)
    narrative, by, notes = await _narrate(db, payload.lang, text, gen.reading_prompt(res, text, payload.lang))
    return AnalysisReadResult(source=source, device_id=payload.device_id if source == "server" else None,
                              hours=payload.hours if source == "server" else None, narrative=narrative, generated_by=by, notes=notes, **res)


