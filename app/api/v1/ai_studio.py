@router.post("/sop/generate", response_model=SOPGenerateResult)
async def generate_sop(payload: SOPGenerateRequest, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    """Generate a device-specific SOP draft from the device, its model's vetted SOP (if any), live
    alarms / work orders / diagnoses / spare-part stock, the latest lab comparison and
    knowledge-base excerpts. The result is always a DRAFT for human review."""
    st = gen.normalize_sop_type(payload.sop_type)
    if not st:
        raise HTTPException(status_code=400, detail="sop_type must be Calibration, Replacement or Maintenance")
    device = _device(db, payload.device_id)
    m = db.get(DeviceModel, device.model_id) if device.model_id else None
    model_name = m.model_name if m else None
    kb = await studio_data.kb_search(db, " ".join(x for x in (model_name, st, payload.component_name, "procedure") if x), 3)
    ctx = studio_data.sop_context(db, device, st, payload.component_name, kb)
    title, template = gen.sop_template(ctx, payload.lang)
    content, by, notes = await _narrate(db, payload.lang, template, gen.sop_prompt(ctx, template, payload.lang))
    if by == "llm" and "DRAFT" not in content and "草稿" not in content:
        content = ("> ⚠ DRAFT — generated by AI, must be reviewed before use.\n\n" if payload.lang == "en" else "> ⚠ 草稿：由 AI 生成，执行前必须审核。\n\n") + content

    sources: list[SourceRef] = []
    if ctx["base_sop"]:
        sources.append(SourceRef(type="sop", id=ctx["base_sop"]["id"], title=ctx["base_sop"]["title"]))
    sources += [SourceRef(type="knowledge", id=k["chunk_id"], document_id=k["document_id"], title=k["document_title"], score=k["score"], excerpt=k["excerpt"]) for k in kb]
    if ctx["last_diagnosis"]:
        sources.append(SourceRef(type="diagnosis", title=ctx["last_diagnosis"]["diagnosis"][:120]))
    if ctx["correlation"]:
        sources.append(SourceRef(type="correlation", title=f"R²={ctx['correlation']['r_squared']}"))

    saved_id = None
    if payload.save:
        row = MaintenanceSOP(device_model_id=device.model_id, sop_type=st, title=title[:200], content=content, version=studio_data.AI_DRAFT_VERSION)
        db.add(row)
        db.commit()
        db.refresh(row)
        saved_id = row.id
    return SOPGenerateResult(
        device_id=device.id, device_code=device.device_code, device_model_id=device.model_id, sop_type=st, title=title, content=content, lang=payload.lang,
        generated_by=by, sources=sources, notes=notes, saved_sop_id=saved_id,
        context={"has_vetted_sop": bool(ctx["base_sop"]), "open_alarms": len(ctx["open_alarms"]), "open_work_orders": len(ctx["open_work_orders"]),
                 "spare_parts": len(ctx["spare_parts"]), "knowledge_hits": len(kb)},
    )


