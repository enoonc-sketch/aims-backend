"""Lifecycle of the bundled PostgreSQL cluster — no psql parsing, no shell quoting.

The Windows installer ships the official PostgreSQL binaries (``pgsql\\bin``) and
this module is the only place that starts, configures, backs up and restores that
cluster. It talks to the server through:

  * ``pg_ctl`` / ``initdb`` / ``pg_dump`` / ``pg_restore`` / ``pg_isready`` — the
    documented command-line interfaces, always with an argument list (never a
    shell string, so a password or a path with a space or ``&`` cannot break out);
  * ``psycopg2`` for SQL — passwords and identifiers are quoted by the driver.

Every method is idempotent and safe to re-run: `configure()` rewrites the managed
include file, `ensure_database()` uses IF NOT EXISTS-style checks, and starting an
already-running cluster is a no-op. That is what lets the installer, the desktop
launcher and the support CLI share one code path.
"""
from __future__ import annotations

import logging
import os
import shutil
import socket
import subprocess
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Sequence

from app.deploy.paths import IS_WINDOWS, Layout, load_layout

logger = logging.getLogger("aims.deploy.pg")

CREATE_NO_WINDOW = 0x08000000 if IS_WINDOWS else 0

MANAGED_BEGIN = "# >>> AIMS MANAGED SETTINGS — do not edit, regenerated by the installer >>>"
MANAGED_END = "# <<< AIMS MANAGED SETTINGS <<<"


class PgError(RuntimeError):
    """A PostgreSQL operation failed; the message is meant for the end user."""


@dataclass
class PgResult:
    args: Sequence[str]
    code: int
    stdout: str
    stderr: str

    @property
    def ok(self) -> bool:
        return self.code == 0

    def tail(self, lines: int = 12) -> str:
        text = (self.stderr or "") + (("\n" + self.stdout) if self.stdout else "")
        parts = [ln for ln in text.strip().splitlines() if ln.strip()]
        return "\n".join(parts[-lines:])

    def raise_for_status(self, what: str) -> "PgResult":
        if not self.ok:
            raise PgError(f"{what} 失败 (退出码 {self.code})：\n{self.tail()}")
        return self


def total_ram_gb() -> float:
    """Physical RAM, best effort, no dependencies (0.0 when unknown)."""
    if os.path.exists("/proc/meminfo"):
        try:
            with open("/proc/meminfo", "r", encoding="utf-8") as f:
                for line in f:
                    if line.startswith("MemTotal:"):
                        return round(int(line.split()[1]) / 1024 / 1024, 1)
        except Exception:
            return 0.0
    if IS_WINDOWS:
        try:
            import ctypes

            class MEMORYSTATUSEX(ctypes.Structure):
                _fields_ = [("dwLength", ctypes.c_ulong), ("dwMemoryLoad", ctypes.c_ulong),
                            ("ullTotalPhys", ctypes.c_ulonglong), ("ullAvailPhys", ctypes.c_ulonglong),
                            ("ullTotalPageFile", ctypes.c_ulonglong), ("ullAvailPageFile", ctypes.c_ulonglong),
                            ("ullTotalVirtual", ctypes.c_ulonglong), ("ullAvailVirtual", ctypes.c_ulonglong),
                            ("ullAvailExtendedVirtual", ctypes.c_ulonglong)]

            stat = MEMORYSTATUSEX()
            stat.dwLength = ctypes.sizeof(MEMORYSTATUSEX)
            if ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(stat)):
                return round(stat.ullTotalPhys / 1024 ** 3, 1)
        except Exception:
            return 0.0
    try:
        import sys
        page = os.sysconf("SC_PAGE_SIZE")
        return round(os.sysconf("SC_PHYS_PAGES") * page / 1024 ** 3, 1)
    except Exception:
        return 0.0


def port_open(host: str, port: int, timeout: float = 0.4) -> bool:
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


def port_free(port: int, host: str = "127.0.0.1") -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            s.bind((host, port))
            return True
        except OSError:
            return False


def _pid_alive(pid: int) -> bool:
    """进程是否还活着（不依赖 psutil，也不发信号真的去动它）。"""
    if pid <= 0:
        return False
    if IS_WINDOWS:
        try:
            import ctypes

            PROCESS_QUERY_LIMITED_INFORMATION = 0x1000
            STILL_ACTIVE = 259
            kernel32 = ctypes.windll.kernel32
            handle = kernel32.OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, False, pid)
            if not handle:
                return False
            try:
                code = ctypes.c_ulong()
                if not kernel32.GetExitCodeProcess(handle, ctypes.byref(code)):
                    return False
                return code.value == STILL_ACTIVE
            finally:
                kernel32.CloseHandle(handle)
        except Exception:  # noqa: BLE001
            return False
    try:
        os.kill(pid, 0)
        return True
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    except OSError:
        return False


class Postgres:
    """One bundled cluster."""

    def __init__(self, layout: Layout | None = None, *, port: int | None = None,
                 superuser: str = "aims_dba", app_user: str = "aims",
                 database: str = "aims", service: str = "AIMSPostgreSQL") -> None:
        self.layout = layout or load_layout()
        self.port = int(port or os.environ.get("AIMS_PG_PORT") or 55432)
        self.superuser = superuser
        self.app_user = app_user
        self.database = database
        self.service = service
        self.host = "127.0.0.1"

    # ------------------------------------------------------------------ paths
    @property
    def data(self) -> Path:
        return self.layout.pg_data

    @property
    def conf_file(self) -> Path:
        return self.data / "postgresql.conf"

    @property
    def managed_conf(self) -> Path:
        return self.data / "aims.conf"

    @property
    def hba_file(self) -> Path:
        return self.data / "pg_hba.conf"

    @property
    def pid_file(self) -> Path:
        return self.data / "postmaster.pid"

    def running_pid(self) -> int | None:
        """PID of *our* postmaster, or None.

        这是"端口上有人应答"和"我们的集群在跑"之间的区别所在。同一台机器上可能
        有别的 PostgreSQL（客户原来的数据库、上一个测试安装、同事的容器）正好占着
        55432；只探测端口会把别人的库当成自己的，然后在认证失败时给出莫名其妙的
        报错。postmaster.pid 只存在于我们自己的数据目录，里面还记着端口号，
        所以它是唯一可靠的判据。
        """
        try:
            lines = self.pid_file.read_text(encoding="utf-8", errors="replace").splitlines()
            pid = int(lines[0].strip())
        except (OSError, ValueError, IndexError):
            return None
        if not _pid_alive(pid):
            return None
        if len(lines) >= 4:
            try:
                if int(lines[3].strip()) != self.port:
                    # 集群在跑，但不在我们以为的端口上（手工改过配置）。
                    return None
            except ValueError:
                pass
        return pid

    def binary(self, name: str) -> Path:
        exe = name + (".exe" if IS_WINDOWS else "")
        return self.layout.pg_bin / exe

    def has_binaries(self) -> bool:
        return self.binary("pg_ctl").is_file() and self.binary("initdb").is_file()

    @property
    def initialized(self) -> bool:
        # PG_VERSION is written by initdb and is the only reliable marker; a
        # half-finished initdb leaves an empty data dir instead.
        return (self.data / "PG_VERSION").is_file()

    # ------------------------------------------------------------------- exec
    def _env(self, password: str | None = None) -> dict[str, str]:
        env = os.environ.copy()
        env["PGCLIENTENCODING"] = "UTF8"
        env["PGCONNECT_TIMEOUT"] = "10"
        env.setdefault("PGTZ", "UTC")
        # Keep client messages/messages English so log scraping is stable, unless
        # the system is explicitly localized for PG.
        if password is not None:
            env["PGPASSWORD"] = password
        # Windows: keep psql/pg_dump from writing to a codepage that mangles UTF-8
        if IS_WINDOWS:
            env.setdefault("PGCLIENTENCODING", "UTF8")
        return env

    def run(self, args: Iterable[str | Path], *, timeout: float = 120, password: str | None = None,
            check: bool = False, cwd: Path | None = None) -> PgResult:
        argv = [str(a) for a in args]
        # subprocess 在 cwd 不存在时抛的也是 FileNotFoundError，会被下面误判成
        # "找不到 PostgreSQL 程序"，把现场运维引向错误方向（实际是安装目录没建）。
        workdir = Path(cwd or self.layout.root)
        if not workdir.is_dir():
            try:
                workdir.mkdir(parents=True, exist_ok=True)
            except OSError as exc:
                raise PgError(f"无法创建工作目录 {workdir}：{exc}") from exc
        try:
            proc = subprocess.run(
                argv,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=timeout,
                env=self._env(password),
                cwd=str(workdir),
                creationflags=CREATE_NO_WINDOW,
            )
        except FileNotFoundError as exc:
            if not Path(argv[0]).exists():
                raise PgError(f"找不到 PostgreSQL 程序：{argv[0]}（安装不完整？）") from exc
            raise PgError(f"无法在工作目录 {workdir} 下运行 {argv[0]}：{exc}") from exc
        except subprocess.TimeoutExpired as exc:
            raise PgError(f"命令超时（{timeout:.0f}s）：{' '.join(argv[:2])}") from exc
        result = PgResult(args=argv, code=proc.returncode, stdout=proc.stdout or "", stderr=proc.stderr or "")
        if check and not result.ok:
            result.raise_for_status(Path(argv[0]).name)
        return result

    def version(self) -> tuple[str, int]:
        res = self.run([self.binary("postgres"), "--version"], timeout=20)
        text = (res.stdout or res.stderr).strip()
        # "postgres (PostgreSQL) 16.4"
        major = 0
        for token in text.replace("(", " ").replace(")", " ").split():
            if token and token[0].isdigit() and "." in token:
                try:
                    major = int(token.split(".")[0])
                except ValueError:
                    major = 0
                break
        return text, major

    # ------------------------------------------------------------------ initdb
    def initdb(self, superuser_password: str, *, quiet: bool = True) -> PgResult:
        if self.initialized:
            return PgResult(args=["initdb"], code=0, stdout="already initialized", stderr="")
        if not self.has_binaries():
            raise PgError(f"PostgreSQL 程序缺失：{self.layout.pg_bin}")
        self.data.parent.mkdir(parents=True, exist_ok=True)
        if self.data.exists() and any(self.data.iterdir()):
            # Only the leftovers of a previously failed initdb can be here; a real
            # cluster always has PG_VERSION (checked above).
            logger.warning("数据目录非空但没有 PG_VERSION，按未初始化处理：%s", self.data)
        pw_dir = Path(tempfile.mkdtemp(prefix="aims-initdb-"))
        pw_file = pw_dir / "pw.txt"
        try:
            pw_file.write_text(superuser_password + "\n", encoding="utf-8")
            args = [
                self.binary("initdb"),
                "-D", self.data,
                "-U", self.superuser,
                f"--pwfile={pw_file}",
                "--encoding=UTF8",
                "--locale=C",
                "--auth-host=scram-sha-256",
                "--auth-local=scram-sha-256",
                "--data-checksums",
            ]
            if quiet:
                args.append("--no-instructions")
            res = self.run(args, timeout=600)
            if not res.ok:
                raise PgError("初始化数据库集群 (initdb) 失败：\n" + res.tail(20))
        finally:
            shutil.rmtree(pw_dir, ignore_errors=True)
        self.configure()
        return res

    # ------------------------------------------------------------- configure
    def configure(self, *, extra: dict[str, str] | None = None) -> Path:
        """(Re)write aims.conf + pg_hba.conf and make postgresql.conf include them."""
        if not self.initialized:
            raise PgError("集群尚未初始化，无法写入配置")
        ram = total_ram_gb() or 8.0
        shared_buffers = int(max(128, min(2048, ram * 256)))          # MB ≈ 25% of RAM
        effective_cache = int(max(512, min(8192, ram * 614)))
        maintenance = int(max(64, min(512, ram * 51)))
        work_mem = 8 if ram < 16 else 16

        settings = {
            "port": str(self.port),
            "listen_addresses": f"'{self.host}'",
            "max_connections": "50",
            "shared_buffers": f"{shared_buffers}MB",
            "effective_cache_size": f"{effective_cache}MB",
            "maintenance_work_mem": f"{maintenance}MB",
            "work_mem": f"{work_mem}MB",
            "temp_buffers": "16MB",
            "max_wal_size": "1GB",
            "min_wal_size": "128MB",
            "checkpoint_timeout": "15min",
            "checkpoint_completion_target": "0.9",
            "random_page_cost": "1.1",
            "effective_io_concurrency": "200",
            "wal_compression": "on",
            "default_statistics_target": "100",
            "timezone": "'UTC'",
            "log_timezone": "'UTC'",
            "datestyle": "'iso, mdy'",
            "lc_messages": "'C'",
            "lc_monetary": "'C'",
            "lc_numeric": "'C'",
            "lc_time": "'C'",
            "password_encryption": "scram-sha-256",
            "logging_collector": "on",
            "log_directory": "'pg_log'",
            "log_filename": "'postgresql-%Y-%m-%d.log'",
            "log_rotation_age": "1d",
            "log_rotation_size": "50MB",
            "log_min_duration_statement": "1000",
            "log_line_prefix": "'%m [%p] '",
            "log_checkpoints": "on",
            "log_lock_waits": "on",
            "autovacuum": "on",
            "jit": "off",
        }
        if not IS_WINDOWS:
            # A bundled cluster must never depend on a system path such as the
            # Debian-built default /var/run/postgresql: it may not exist, may not be
            # writable by the installing account, and a second install would collide.
            # Keeping the socket inside the data directory makes the tree relocatable
            # and lets a non-admin POSIX run work (Windows has no unix sockets at all).
            settings["unix_socket_directories"] = f"'{self.data.as_posix()}'"
        if extra:
            settings.update({k: str(v) for k, v in extra.items()})

        lines = [MANAGED_BEGIN,
                 f"# generated {time.strftime('%Y-%m-%d %H:%M:%S')} — host RAM {ram} GB",
                 ""]
        lines += [f"{k} = {v}" for k, v in settings.items()]
        lines += ["", MANAGED_END, ""]
        self.managed_conf.write_text("\n".join(lines), encoding="utf-8")

        # postgresql.conf: make sure our include is there exactly once.
        conf = self.conf_file.read_text(encoding="utf-8", errors="replace")
        include_line = "include_if_exists = 'aims.conf'"
        if include_line not in conf:
            with open(self.conf_file, "a", encoding="utf-8") as f:
                f.write(f"\n# --- AIMS: managed settings live in aims.conf (kept separate so\n"
                        f"#     re-running the installer never rewrites this file) ---\n{include_line}\n")

        # pg_hba.conf: loopback + (POSIX only) local socket, password auth only.
        hba = ["# AIMS managed access rules — local machine only, password required",
               "# TYPE  DATABASE        USER            ADDRESS                 METHOD"]
        if not IS_WINDOWS:
            hba.append("local   all             all                                     scram-sha-256")
        hba += [
            f"host    all             {self.app_user}      127.0.0.1/32            scram-sha-256",
            f"host    all             {self.superuser}      127.0.0.1/32            scram-sha-256",
            "host    all             all             127.0.0.1/32            reject",
            "host    all             all             ::1/128                 scram-sha-256",
            "# everything else (LAN, internet) is refused: the cluster is single-machine",
            "host    all             all             all                     reject",
        ]
        self.hba_file.write_text("\n".join(hba) + "\n", encoding="utf-8")
        return self.managed_conf

    # ------------------------------------------------------------------ start
    def status(self) -> str:
        """'uninitialized' | 'running' | 'stopped' | 'unknown'."""
        if not self.initialized:
            return "uninitialized"
        if not self.has_binaries():
            return "unknown"
        # postmaster.pid 存在且进程活着就是 running：pg_ctl status 在权限受限、
        # 或数据目录所属账户与当前账户不同时可能返回非 0/3 的怪值，我们不该因此
        # 把"其实在跑"的库报成 unknown。
        if self.running_pid() is not None:
            return "running"
        res = self.run([self.binary("pg_ctl"), "-D", self.data, "status"], timeout=20)
        if res.code == 0:
            return "running"
        if res.code == 3:
            return "stopped"
        return "unknown"

    def is_ready(self, timeout: float = 2.0) -> bool:
        # 先用 postmaster.pid 确认端口上应答的确实是**我们的**集群，再看它是否接受连接。
        if self.running_pid() is None:
            return False
        if not port_open(self.host, self.port, timeout=min(timeout, 0.5)):
            return False
        res = self.run([self.binary("pg_isready"), "-h", self.host, "-p", str(self.port),
                        "-U", self.superuser, "-d", "postgres", "-q"], timeout=timeout)
        # 0 = accepting, 1 = rejecting (still starting) -> treat 1 as not ready yet
        return res.code == 0

    def wait_ready(self, timeout: float = 90.0, interval: float = 0.5) -> bool:
        deadline = time.time() + timeout
        while time.time() < deadline:
            if self.is_ready():
                return True
            time.sleep(interval)
        return False

    def start(self, *, wait: float = 90.0, log_file: Path | None = None) -> bool:
        """Start the cluster with pg_ctl. Returns True if it is (now) ready."""
        if self.is_ready():
            return True
        if not self.initialized:
            raise PgError("数据库集群尚未初始化，请先运行安装程序或 `deploy provision`")
        if self.status() == "running":
            # Running but not accepting connections (still crashing on startup?);
            # give it the benefit of the readiness wait instead of a second start.
            return self.wait_ready(wait)
        if port_open(self.host, self.port):
            # 端口有人应答，但不是我们的 postmaster：pd_ctl 会在日志里报
            # "Address already in use"，用户看不懂。这里直接给可执行的说明。
            raise PgError(
                f"端口 {self.port} 已被其它程序占用（不是本机 AIMS 数据库）。\n"
                f"请关闭占用该端口的程序，或修改 {self.layout.env_file} 里的 AIMS_PG_PORT 后重试。"
            )
        self.layout.logs_dir.mkdir(parents=True, exist_ok=True)
        log = log_file or (self.layout.logs_dir / "pgsql-startup.log")
        res = self.run([self.binary("pg_ctl"), "-D", self.data, "-l", log, "-w", "-t", str(int(wait)), "start"],
                       timeout=wait + 30)
        if not res.ok:
            raise PgError("启动数据库失败：\n" + res.tail(20) +
                          f"\n服务器日志：{self.data / 'pg_log'} 或 {log}")
        return self.wait_ready(min(wait, 30))

    def stop(self, *, mode: str = "fast", wait: float = 60.0) -> bool:
        if not self.initialized or self.status() != "running":
            return True
        res = self.run([self.binary("pg_ctl"), "-D", self.data, "-m", mode, "-w", "-t", str(int(wait)), "stop"],
                       timeout=wait + 30)
        if not res.ok:
            raise PgError("停止数据库失败：\n" + res.tail(12))
        return True

    def restart(self, *, wait: float = 90.0) -> bool:
        self.stop()
        return self.start(wait=wait)

    # -------------------------------------------------------------------- SQL
    def connect(self, *, database: str | None = None, user: str | None = None,
                password: str, autocommit: bool = True):
        import psycopg2

        return psycopg2.connect(
            host=self.host, port=self.port, dbname=database or self.database,
            user=user or self.superuser, password=password,
            connect_timeout=15, application_name="aims-deploy",
        )

    def ensure_database(self, *, superuser_password: str, app_password: str) -> dict[str, Any]:
        """Create the superuser-visible database, the app role and extensions.

        Idempotent: re-running an upgrade never touches existing data, only adds
        what is missing.
        """
        from psycopg2 import sql

        info: dict[str, Any] = {"created_db": False, "created_role": False,
                                "extensions": [], "vector": False, "timescale": False}
        conn = self.connect(database="postgres", user=self.superuser, password=superuser_password)
        conn.autocommit = True
        try:
            with conn.cursor() as cur:
                cur.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (self.app_user,))
                if cur.fetchone() is None:
                    cur.execute(sql.SQL("CREATE ROLE {} LOGIN PASSWORD {}").format(
                        sql.Identifier(self.app_user), sql.Literal(app_password)))
                    info["created_role"] = True
                else:
                    # keep the role's password in sync with secrets.json (restore case)
                    cur.execute(sql.SQL("ALTER ROLE {} WITH LOGIN PASSWORD {}").format(
                        sql.Identifier(self.app_user), sql.Literal(app_password)))
                cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (self.database,))
                if cur.fetchone() is None:
                    cur.execute(sql.SQL("CREATE DATABASE {} OWNER {} ENCODING 'UTF8' TEMPLATE template0").format(
                        sql.Identifier(self.database), sql.Identifier(self.app_user)))
                    info["created_db"] = True
                cur.execute("SELECT 1 FROM pg_available_extensions WHERE name = 'vector'")
                vector_available = cur.fetchone() is not None
                cur.execute("SELECT 1 FROM pg_available_extensions WHERE name = 'timescaledb'")
                timescale_available = cur.fetchone() is not None
        finally:
            conn.close()

        # Extensions are per-database, so install them inside the app database.
        conn = self.connect(database=self.database, user=self.superuser, password=superuser_password)
        conn.autocommit = True
        try:
            with conn.cursor() as cur:
                for ext in ("vector", "pg_trgm", "timescaledb"):
                    if ext == "vector" and not vector_available:
                        continue
                    if ext == "timescaledb" and not timescale_available:
                        continue
                    try:
                        cur.execute(f'CREATE EXTENSION IF NOT EXISTS "{ext}"')
                        info["extensions"].append(ext)
                    except Exception as exc:  # noqa: BLE001
                        logger.warning("扩展 %s 安装失败：%s", ext, exc)
                        conn.rollback()
                cur.execute("SELECT extname FROM pg_extension")
                installed = {r[0] for r in cur.fetchall()}
                info["vector"] = "vector" in installed
                info["timescale"] = "timescaledb" in installed
                # make sure the app role can create its own objects (it owns the DB)
                cur.execute(sql.SQL("GRANT ALL ON SCHEMA public TO {}").format(sql.Identifier(self.app_user)))
        finally:
            conn.close()
        return info

    def scalar(self, sql_text: str, *, password: str, database: str | None = None,
               user: str | None = None) -> Any:
        conn = self.connect(database=database, user=user, password=password)
        try:
            with conn.cursor() as cur:
                cur.execute(sql_text)
                row = cur.fetchone()
                return row[0] if row else None
        finally:
            conn.close()

    def execute(self, statements: Sequence[str], *, password: str, database: str | None = None,
                user: str | None = None) -> None:
        conn = self.connect(database=database, user=user, password=password)
        conn.autocommit = True
        try:
            with conn.cursor() as cur:
                for stmt in statements:
                    if stmt.strip():
                        cur.execute(stmt)
        finally:
            conn.close()

    # ------------------------------------------------------------ dump/restore
    def dump(self, dest: Path, *, password: str) -> Path:
        """Custom-format logical dump (pg_dump -Fc) — the restore path for backups
        and for major-version upgrades."""
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = dest.with_suffix(dest.suffix + ".part")
        res = self.run([self.binary("pg_dump"), "-h", self.host, "-p", str(self.port),
                        "-U", self.superuser, "-d", self.database,
                        "-Fc", "-Z", "6", "--no-owner", "--no-privileges",
                        "-f", tmp], password=password, timeout=3600)
        if not res.ok:
            try:
                tmp.unlink(missing_ok=True)
            except OSError:
                pass
            raise PgError("备份数据库失败：\n" + res.tail(20))
        os.replace(tmp, dest)
        return dest

    def dump_ok(self, path: Path) -> bool:
        """Verify a custom dump without touching the live cluster (pg_restore -l)."""
        res = self.run([self.binary("pg_restore"), "-l", path], timeout=600)
        return res.ok and "Archive created at" in res.stdout

    def restore(self, src: Path, *, password: str, clean: bool = True) -> None:
        """Restore into the app database. `clean` drops the objects first (pg_restore -c)."""
        args = [self.binary("pg_restore"), "-h", self.host, "-p", str(self.port),
                "-U", self.superuser, "-d", self.database,
                "--no-owner", "--no-privileges", "--single-transaction"]
        if clean:
            args += ["--clean", "--if-exists"]
        args.append(src)
        res = self.run(args, password=password, timeout=7200)
        if not res.ok:
            # pg_restore warns about missing objects during --clean; only real
            # errors (exit code > 1) are fatal.
            if res.code >= 2 or "error:" in res.stderr.lower():
                raise PgError("恢复数据库失败：\n" + res.tail(25))
            logger.warning("恢复过程中出现警告（已忽略）：\n%s", res.tail(10))
        # 归档是用 --no-owner 恢复的，对象会归到"执行恢复的连接账号"（超级用户）名下。
        # 不修正的话，应用账号连自己的表都不能写 —— 表现为恢复后一切"能打开但改不了"，
        # 而且日志里全是 permission denied，非常难定位。
        self.normalize_ownership(password=password)

    def normalize_ownership(self, *, password: str) -> None:
        """把库内对象归属与权限收敛回应用账号。

        为什么不用 `REASSIGN OWNED BY aims_dba TO aims`：扩展（pgvector）的对象也
        属于超级用户，而扩展对象的所有者不允许转移，整条 REASSIGN 会直接失败，
        结果"一条都没改"。所以这里逐表/逐序列/逐视图改属主，只动业务对象。
        """
        fix = f"""
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I OWNER TO {self.app_user}', r.tablename);
  END LOOP;
  FOR r IN SELECT sequence_name FROM information_schema.sequences
           WHERE sequence_schema = 'public' LOOP
    EXECUTE format('ALTER SEQUENCE public.%I OWNER TO {self.app_user}', r.sequence_name);
  END LOOP;
  FOR r IN SELECT viewname FROM pg_views WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER VIEW public.%I OWNER TO {self.app_user}', r.viewname);
  END LOOP;
END $$;
"""
        statements = [
            fix,
            f'GRANT ALL ON SCHEMA public TO "{self.app_user}"',
            f'GRANT ALL ON ALL TABLES IN SCHEMA public TO "{self.app_user}"',
            f'GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO "{self.app_user}"',
            f'GRANT ALL ON ALL FUNCTIONS IN SCHEMA public TO "{self.app_user}"',
            f'ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO "{self.app_user}"',
            f'ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO "{self.app_user}"',
        ]
        failed = 0
        for stmt in statements:
            try:
                self.execute([stmt], password=password)
            except Exception as exc:  # noqa: BLE001
                failed += 1
                logger.warning("权限修正失败：%s", exc)
        if failed:
            logger.warning("有 %d 条权限修正未成功，应用可能无法写入部分表", failed)

    # -------------------------------------------------------------- utilities
    def database_size_mb(self, *, password: str) -> float:
        try:
            val = self.scalar(f"SELECT pg_database_size('{self.database}')", password=password, database="postgres")
            return round((val or 0) / 1024 / 1024, 1)
        except Exception:
            return 0.0

    def settings_snapshot(self, *, password: str) -> dict[str, str]:
        out: dict[str, str] = {}
        try:
            conn = self.connect(database="postgres", password=password)
            try:
                with conn.cursor() as cur:
                    cur.execute("SHOW data_directory")
                    out["data_directory"] = cur.fetchone()[0]
                    cur.execute("SHOW port")
                    out["port"] = cur.fetchone()[0]
                    cur.execute("SHOW server_version")
                    out["server_version"] = cur.fetchone()[0]
                    cur.execute("SHOW shared_buffers")
                    out["shared_buffers"] = cur.fetchone()[0]
            finally:
                conn.close()
        except Exception as exc:
            out["error"] = str(exc)
        return out
